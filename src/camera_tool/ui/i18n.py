DEFAULT_LANG = "en"
LANG_OPTIONS = (("en", "EN"), ("zh", "中文"))


def normalize_lang(lang: str | None) -> str:
    value = str(lang or DEFAULT_LANG).strip().lower()
    return "zh" if value.startswith("zh") else "en"


def resolve_initial_lang() -> str:
    return normalize_lang(os.environ.get("CAMERA_TOOL_LANG", DEFAULT_LANG))


